/* ============================================================
   Рендерер фигур
   ============================================================ */
const FIG = (() => {
  const NS = 'http://www.w3.org/2000/svg';
  const C_NEAR = '#F2F2F2', C_FAR = '#5A5A60', C_RED = '#FF2A3A', C_RED_FAR = '#8E1420', C_PROP = '#A9A9B0';
  const live = new Set();
  const el = (tag, attrs, parent) => { const e = document.createElementNS(NS, tag); for (const k in attrs) e.setAttribute(k, attrs[k]); if (parent) parent.appendChild(e); return e; };
  const ease = t => (1 - Math.cos(Math.PI * t)) / 2;
  const lerp = (a, b, t) => [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t];

  function build(svg, exId, opts = {}) {
    const ex = EX[exId]; if (!ex) return;
    const set = POSES[ex.pose];
    svg.setAttribute('viewBox', set.vb || '0 0 100 100');
    svg.innerHTML = '';
    const hil = new Set(ex.hil);
    const front = !!set.front;
    const g = el('g', {fill:'none','stroke-linecap':'round','stroke-linejoin':'round'}, svg);
    if (!set.nofloor) {
      el('line', {x1:4,y1:91.5,x2:96,y2:91.5,stroke:'#2A2A2E','stroke-width':1.4}, g);
    }
    const shadow = set.nofloor ? null : el('ellipse', {cx:50,cy:91.5,rx:22,ry:2.6,fill:'rgba(255,42,58,.16)',stroke:'none'}, g);
    if (set.wall) el('line', {x1:set.wall,y1:4,x2:set.wall,y2:91.5,stroke:'#3A3A40','stroke-width':3}, g);
    if (set.pullbar !== undefined) { el('line', {x1:28,y1:set.pullbar,x2:72,y2:set.pullbar,stroke:C_PROP,'stroke-width':3}, g); }
    if (set.bench) { const [x,y,w] = set.bench; el('rect', {x,y,width:w,height:5,rx:2.5,fill:'#3A3A40',stroke:'none'}, g); el('line',{x1:x+4,y1:y+5,x2:x+4,y2:91,stroke:'#3A3A40','stroke-width':2.4},g); el('line',{x1:x+w-4,y1:y+5,x2:x+w-4,y2:91,stroke:'#3A3A40','stroke-width':2.4},g); }
    const sw = opts.sw || 6.5;
    const col = (seg, far) => hil.has(seg) ? (far && !front ? C_RED_FAR : C_RED) : (far && !front ? C_FAR : C_NEAR);
    const mk = (seg, far) => el('path', {stroke: col(seg, far), 'stroke-width': sw}, g);
    const E = {};
    E.thigh2 = mk('thigh', 1); E.shin2 = mk('shin', 1); E.upper2 = mk('upper', 1); E.fore2 = mk('fore', 1);
    if (ex.eq === 'db') E.db2 = el('rect', {width:11,height:4.6,rx:2,fill:'#77777E',stroke:'none'}, g);
    E.torso = el('path', {stroke: col('torso'), 'stroke-width': sw + 1}, g);
    E.head = el('circle', {r: 6.5, fill: C_NEAR, stroke: 'none'}, g);
    E.hip = hil.has('hip') ? el('circle', {r: 4.6, fill: C_RED, stroke: 'none'}, g) : null;
    E.thigh1 = mk('thigh'); E.shin1 = mk('shin'); E.upper1 = mk('upper'); E.fore1 = mk('fore');
    if (ex.eq === 'db') E.db1 = el('rect', {width:11,height:4.6,rx:2,fill:C_PROP,stroke:'none'}, g);
    if (ex.eq === 'bar') { E.plate = el('circle', {r:8,fill:'none',stroke:C_PROP,'stroke-width':3}, g); E.plateIn = el('circle', {r:2,fill:C_PROP,stroke:'none'}, g); }
    svg._f = {set, ex, E, shadow, t0: performance.now() - Math.random() * 400, still: false};
    draw(svg, null);
    live.add(svg);
  }

  function poseAt(set, t) {
    const F = set.f, N = F.length, D = set.d * 1000, u = (((t % D) + D) % D) / D * N;
    const i = Math.floor(u) % N, k = ease(u - Math.floor(u));
    const A = F[i], B = F[(i + 1) % N], o = {};
    for (const key of ['h','n','p','k1','a1','t1','k2','a2','t2','e1','w1','e2','w2']) o[key] = lerp(A[key], B[key], k);
    const mA = A.m || lerp(A.n, A.p, .5), mB = B.m || lerp(B.n, B.p, .5);
    o.m = lerp(mA, mB, k);
    return o;
  }
  const L = (...pts) => 'M' + pts.map(p => p[0].toFixed(1) + ' ' + p[1].toFixed(1)).join(' L');

  function placeDb(rect, e, w) {
    const ang = Math.atan2(w[1] - e[1], w[0] - e[0]) * 180 / Math.PI + 90;
    rect.setAttribute('x', w[0] - 5.5); rect.setAttribute('y', w[1] - 2.3);
    rect.setAttribute('transform', `rotate(${ang.toFixed(1)} ${w[0].toFixed(1)} ${w[1].toFixed(1)})`);
  }

  function draw(svg, now) {
    const f = svg._f; if (!f) return;
    const t = now === null ? 0 : now - f.t0;
    const o = poseAt(f.set, t);
    const E = f.E;
    E.thigh2.setAttribute('d', L(o.p, o.k2)); E.shin2.setAttribute('d', L(o.k2, o.a2, o.t2));
    E.upper2.setAttribute('d', L(o.n, o.e2)); E.fore2.setAttribute('d', L(o.e2, o.w2));
    E.torso.setAttribute('d', `M${o.n[0].toFixed(1)} ${o.n[1].toFixed(1)} Q${(2*o.m[0]-(o.n[0]+o.p[0])/2).toFixed(1)} ${(2*o.m[1]-(o.n[1]+o.p[1])/2).toFixed(1)} ${o.p[0].toFixed(1)} ${o.p[1].toFixed(1)}`);
    E.head.setAttribute('cx', o.h[0].toFixed(1)); E.head.setAttribute('cy', o.h[1].toFixed(1));
    if (E.hip) { E.hip.setAttribute('cx', o.p[0].toFixed(1)); E.hip.setAttribute('cy', o.p[1].toFixed(1)); }
    E.thigh1.setAttribute('d', L(o.p, o.k1)); E.shin1.setAttribute('d', L(o.k1, o.a1, o.t1));
    E.upper1.setAttribute('d', L(o.n, o.e1)); E.fore1.setAttribute('d', L(o.e1, o.w1));
    if (E.db1) { placeDb(E.db1, o.e1, o.w1); placeDb(E.db2, o.e2, o.w2); }
    if (E.plate) { const c = f.set.barAt === 'n' ? [o.n[0] - 2, o.n[1] - 1] : o.w1; E.plate.setAttribute('cx', c[0].toFixed(1)); E.plate.setAttribute('cy', c[1].toFixed(1)); E.plateIn.setAttribute('cx', c[0].toFixed(1)); E.plateIn.setAttribute('cy', c[1].toFixed(1)); }
    if (f.shadow) { const xs = [o.a1[0], o.a2[0], o.w1[0], o.p[0]]; const cx = (Math.min(...xs) + Math.max(...xs)) / 2; f.shadow.setAttribute('cx', cx.toFixed(1)); }
  }

  function loop(now) {
    for (const svg of live) {
      if (!svg.isConnected) { live.delete(svg); continue; }
      if (svg._f.still) continue;
      if (svg.getClientRects().length === 0) continue;
      draw(svg, now);
    }
    requestAnimationFrame(loop);
  }
  requestAnimationFrame(loop);

  /* создаёт <svg data-ex="id"> в строке HTML; mount() оживляет */
  const html = (id, cls = 'fig') => `<svg class="${cls}" data-ex="${id}" viewBox="0 0 100 100"></svg>`;
  const mount = (root = document) => root.querySelectorAll('svg[data-ex]').forEach(s => { if (!s._f) build(s, s.dataset.ex); });
  const at = (svg, ms) => { svg._f.still = true; draw(svg, svg._f.t0 + ms); };
  return {build, html, mount, at};
})();
